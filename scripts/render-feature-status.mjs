#!/usr/bin/env node
/**
 * Renders docs/FEATURE-STATUS.md from features/status.json.
 *
 *   node scripts/render-feature-status.mjs          # write
 *   node scripts/render-feature-status.mjs --check  # CI: fail on drift
 *
 * The JSON is the source of truth; the Markdown is generated so the README
 * cannot silently drift from the audited status.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(fileURLToPath(new URL("..", import.meta.url)));
const source = JSON.parse(readFileSync(resolve(root, "features/status.json"), "utf8"));
const target = resolve(root, "docs/FEATURE-STATUS.md");
const allowed = new Set(["implemented", "partial", "ui-only", "absent", "not-established"]);

for (const item of source.components) {
  if (!allowed.has(item.status)) throw new Error(`Unknown status for ${item.name}: ${item.status}`);
  if (!item.name || !item.evidence) throw new Error("Every component needs a name and evidence");
}

const counts = {};
for (const item of source.components) counts[item.status] = (counts[item.status] ?? 0) + 1;
const summary = Object.entries(counts)
  .map(([status, count]) => `${count} ${status}`)
  .join(" · ");

const rows = source.components
  .map((item) => `| ${item.status} | ${item.name} | ${item.evidence.replace(/\|/g, "\\|")} |`)
  .join("\n");

const body = `# Feature Status

> Generated from [\`features/status.json\`](../features/status.json) on ${source.updated}. Do not edit this file by hand; run \`node scripts/render-feature-status.mjs\`.

**${source.components.length} components:** ${summary}

| Status | Component | Evidence |
| :--- | :--- | :--- |
${rows}

## Legend

${Object.entries(source.legend)
  .map(([status, meaning]) => `- **${status}** — ${meaning}`)
  .join("\n")}

A claim is only as good as its evidence. If a component is not listed here, it
has not been assessed; do not infer that it exists.
`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {
    console.error("docs/FEATURE-STATUS.md is missing; run without --check to generate it.");
    process.exit(1);
  }
  if (current !== body) {
    console.error("docs/FEATURE-STATUS.md is out of date; run node scripts/render-feature-status.mjs.");
    process.exit(1);
  }
  console.log(`ok ${source.components.length} components`);
} else {
  writeFileSync(target, body);
  console.log(`wrote ${target}`);
}
